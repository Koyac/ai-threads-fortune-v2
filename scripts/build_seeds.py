"""
連載の「種」を全話ぶん作って seeds.jsonl に書き出すスクリプト。

企画が始まる前に、これ1回だけ実行する（毎日実行するスクリプトではない）。
post.py が日々の投稿を作るとき、この seeds.jsonl の先頭から1件ずつ取り出して消費していく。

実行方法:
    python scripts/build_seeds.py

--- 連載型について ---

以前は「発信の柱 × 業務 × 詰まりポイント」の独立したTipsを毎回作っていた。
14日・39投稿でフォロワーが1人も増えなかったため、形式そのものを変えた。

Tipsは読んだ瞬間に価値を受け取り終わるので、次を待つ理由が生まれない。
そこで「1つの業務をAIで潰すまで」を数話に分けて連載する形にした。
着手 → つまずき → 解決 → 結果 の順に進み、話が途中で終わるので続きが気になる。

seeds.jsonl は**シャッフルしない**。話数の順番がそのまま投稿順になる。
"""

import json
from pathlib import Path

# このファイル (scripts/build_seeds.py) から見て1つ上の階層がリポジトリのルート。
# GitHub Actions からでもローカルからでも、どこから実行しても正しい場所に書き出せるようにしている。
ROOT = Path(__file__).resolve().parent.parent
SEEDS_PATH = ROOT / "seeds.jsonl"


# --- 話数の型 ---
# 1つの業務につきこの4話で1本の連載になる。role は投稿ログの "pillar" に入るので、
# 週次集計(aggregate.py)は「どの話数が読まれやすいか」を比べられる。
EPISODES = [
    {
        "role": "着手",
        "goal": "これから何を潰すかを宣言する。今どれだけ面倒で、どれだけ時間がかかっているかを書く。"
                "解決策はまだ書かない。「やってみます」で終える。",
    },
    {
        "role": "つまずき",
        "goal": "やってみたらどう失敗したかを書く。AIの出力の何がダメだったかを具体的に。"
                "ここが連載でいちばん人間味が出る話数。うまくいった話にしない。",
    },
    {
        "role": "解決",
        "goal": "どう抜けたかを書く。効いた指示や手順を、読者が再現できる形で渡す。"
                "ここだけはプロンプト全文を載せてよい。",
    },
    {
        "role": "結果",
        "goal": "どうなったかを書く。何分が何分になったか、まだ残っている手作業は何か。"
                "きれいに終わらせず、残った課題を1つ書く。",
    },
]


# --- 連載の題材 ---
# (業務, その業務で具体的に面倒なこと) の組。1組が1本の連載になる。
# 同じ業務でも困りごとが違えば別の連載として成立するので、業務あたり2本ずつ用意している。
# 初期の投稿は、メールだけに偏らないように広く仕事で共感される題材を先頭に並べる。
# これにより、最初の1〜10本で「自分にも当てはまる」「他の業務にも使える」と感じてもらいやすくなる。
ARCS = [
    # 初期の入り口は「広く刺さる仕事の悩み」を優先する
    ("議事録", "会議のあと清書に30分持っていかれる"),
    ("報告書・日報", "夕方に書く気力が残っていない"),
    ("タスク管理", "やることは分かっているのに着手できない"),
    ("長い資料・PDFを読む", "全部読む時間がないが飛ばすのも怖い"),
    ("アイデア出し", "既視感のある案しか出てこない"),
    ("会議の準備・想定問答", "聞かれて困る質問を事前に潰せていない"),
    ("スケジュール調整", "候補日を出すだけの往復が続く"),
    ("判断・優先順位づけ", "その日の気分で順番が変わる"),
    ("抜け漏れの洗い出し", "確認が面倒でつい後回しにする"),
    ("メール返信", "定型的なやり取りに1通10分かかる"),
    ("メール返信", "断りの文面だけ異様に時間がかかる"),
    ("企画書・提案書", "白紙から構成を考えるのが重い"),
    ("企画書・提案書", "上司に出すと毎回同じ指摘で差し戻る"),
    ("資料作成（スライド）", "1枚に何を書くか迷って進まない"),
    ("チャット/Slackの返信", "細かい確認の往復が積み重なる"),
    ("長文の下書き", "書き始めの1段落で止まる"),
    # 読む・調べる
    ("長い資料・PDFを読む", "読んだのに要点を人に説明できない"),
    ("調べ物の裏取り・事実確認", "AIの答えが本当か確かめる手間のほうが大きい"),
    ("競合・市場のリサーチ", "情報を集めすぎて整理で力尽きる"),
    ("情報収集・記事の要約", "後で読もうとして結局読まない"),
    # 数える・扱う
    ("Excel・スプレッドシートの関数", "やりたいことは言えるが関数が書けない"),
    ("Excel・スプレッドシートの関数", "他人が作った式が読めない"),
    ("数字・データの整理", "毎月同じ集計を手作業でやっている"),
    ("グラフ・数値の読み解き", "数字を見ても何を言えばいいか分からない"),
    # 整える・確かめる
    ("誤字脱字・文章のチェック", "自分の文章のミスに気づけない"),
    ("文章の言い換え・トーン調整", "相手によって書き分けるのに毎回悩む"),
    # 考える
    ("考えの整理・壁打ち", "頭の中が散らかったまま人に相談してしまう"),
    # 伝える・備える
    ("説明・プレゼンの組み立て", "話す順番が決まらず何度も作り直す"),
    ("英語のメール・翻訳", "失礼になっていないか自信が持てない"),
    ("問い合わせ・クレーム対応", "感情的な文面に引きずられて時間を使う"),
    # 段取り
    ("手順書・マニュアル作成", "自分は分かっているので何を書くべきか見えない"),
    ("学習・スキルアップ", "何から手をつけるか決められない"),
]


def build_seeds() -> list[dict]:
    """連載ごとに、話数の順で種を並べて返す。

    ここでシャッフルしないのが以前との最大の違い。話数は順番に出さないと連載にならない。
    post.py も「未使用のうち先頭」を順に取るので、この並びがそのまま投稿順になる。
    """
    seeds = []
    n = 0
    for arc_no, (task, pain) in enumerate(ARCS, start=1):
        for ep_no, ep in enumerate(EPISODES, start=1):
            n += 1
            seeds.append({
                "id": f"s{n:04d}",       # s0001, s0002, ... のような連番ID
                "arc_no": arc_no,        # 何本目の連載か
                "arc_total": len(EPISODES),
                "episode": ep_no,        # その連載の何話目か
                # 以下3つは投稿ログのフィールド名に合わせている(週次集計がこの名前で読む)。
                "pillar": ep["role"],    # 話数の役割(着手/つまずき/解決/結果)
                "task": task,            # 連載の題材となる業務
                "pain": pain,            # その業務で具体的に面倒なこと
                "goal": ep["goal"],      # この話数で書くべきこと
                "used": False,           # post.py がこの種を使ったら True にする
            })
    return seeds


def main() -> None:
    if SEEDS_PATH.exists() and SEEDS_PATH.read_text(encoding="utf-8").strip():
        print(f"[build_seeds] {SEEDS_PATH} は既に存在し、空ではありません。上書きを避けるため何もしませんでした。")
        print("[build_seeds] 作り直したい場合は、先に既存の seeds.jsonl を削除してから実行してください。")
        return

    seeds = build_seeds()
    with SEEDS_PATH.open("w", encoding="utf-8") as f:
        for seed in seeds:
            f.write(json.dumps(seed, ensure_ascii=False) + "\n")
    print(f"[build_seeds] {len(ARCS)}本の連載 × {len(EPISODES)}話 = {len(seeds)}件を {SEEDS_PATH} に書き出しました。")


if __name__ == "__main__":
    main()
